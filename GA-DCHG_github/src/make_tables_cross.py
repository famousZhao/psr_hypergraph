"""Generate macros.tex and tables/*.tex for the GA-DCHG cross-domain paper.

Reads results/cross_screen.json, results/cross_{proto}.json and
results/audit_{proto}.json. Every number cited in the prose resolves to a macro;
every table is rebuilt from the same JSON files.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
MAN = ROOT / "manuscript_gad"
TAB = MAN / "tables"
TAB.mkdir(parents=True, exist_ok=True)

_DIG = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
        "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}

PROTO = {"cwru_03": ("C03", r"cwru\_03"), "cwru_0123": ("C0123", r"cwru\_0123")}
DESC = ["kappa", "chi", "rho"]
DESCL = {"kappa": r"$\kappa$", "chi": r"$\chi$", "rho": r"$\rho$"}
DESCN = {"kappa": "curvature", "chi": "expansion", "rho": "filling"}

MODELS = ["cnn", "dynhg", "gad", "gad_noalign", "gad_notemporal", "gad_noanchor"]
MLABEL = {"cnn": "1D-CNN", "dynhg": "DynHGNN+", "gad": "GA-DCHG",
          "gad_noalign": "GA-DCHG $-align$", "gad_notemporal": "GA-DCHG $-temporal$",
          "gad_noanchor": "GA-DCHG $-anchor$"}
MTAG = {"cnn": "Cnn", "dynhg": "Dynhg", "gad": "Gad", "gad_noalign": "Align",
        "gad_notemporal": "Temp", "gad_noanchor": "Anchor"}

# Two positive CWRU load-shift protocols appear in the main tables.
PRIMARY = ("cwru_03", "cwru_0123")

macros = ["% AUTO-GENERATED by src/make_tables_cross.py. Do not edit by hand.",
          "% Every number in the GA-DCHG manuscript resolves to one of these macros.", ""]


def _tex_name(name):
    return "".join(_DIG.get(ch, ch) for ch in name)


def mac(name, val, comment=""):
    if val is None:
        return
    macros.append(f"\\newcommand{{\\{_tex_name(name)}}}{{{val}}}  % {comment}")


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def load(name):
    f = RES / name
    return json.loads(f.read_text()) if f.exists() else None


# ---------------------------------------------------------------- setup
mac("PSRDim", "3", "embedding dimension")
mac("SegLen", "64", "state points per local segment")
mac("NSeg", "4", "local segments per window")
mac("KSeg", "8", "dynamical neighbourhood order")
mac("KMax", "12", "maximal hyperedge size")
mac("Eta", "1.0", "anchor strength in the modulated distance")
mac("Tau", "0.5", "temporal smoothing on the anchor state")
mac("LamAlign", "0.5", "weight of the Wasserstein alignment term")
mac("Epochs", "60", "training epochs")
mac("Batch", "16", "batch size")
mac("LR", r"2\times10^{-3}", "learning rate (math body)")
mac("AlignEpoch", "0", "alignment active from this epoch")

# ---------------------------------------------------------------- screen
screen = load("cross_screen.json")
if screen:
    macros.append("% ---- Component 1 anchor screening ----")
    for proto, (code, _) in PROTO.items():
        if proto not in screen:
            continue
        for d in DESC:
            mac(f"WOne{code}{DESCN[d].capitalize()}", f3(screen[proto][d]["w1"]),
                f"{proto} {d} normalized W1")
        mac(f"Anchor{code}", DESCN[screen[proto]["_anchor"]],
            f"{proto} selected anchor")
        mac(f"NonAnchor{code}", DESCN[screen[proto]["_nonanchor"]],
            f"{proto} least-invariant descriptor")

# ---------------------------------------------------------------- cross results
cross = {p: load(f"cross_{p}.json") for p in PROTO}
done = [p for p in PROTO if cross.get(p)]
if done:
    macros.append("% ---- cross-domain accuracy and gaps ----")
    for proto, (code, _) in PROTO.items():
        j = cross.get(proto)
        if not j:
            continue
        for m in MODELS:
            cell = j.get(m)
            if not cell:
                continue
            mac(f"XAcc{code}{MTAG[m]}", f3(cell["acc"]), f"{proto} {m} target acc")
            mac(f"XSd{code}{MTAG[m]}", f3(cell["acc_std"]), f"{proto} {m} seed std")
            mac(f"XGap{code}{MTAG[m]}", f3(cell["gap_cnn"]),
                f"{proto} {m} target acc minus 1D-CNN")
        sd = [j[m]["acc_std"] for m in MODELS if j.get(m)]
        mac(f"SdMax{code}", f3(max(sd)), f"{proto} max seed std over models")
        for m, tag in (("cnn", "Cnn"), ("dynhg", "Dynhg"), ("gad", "Gad")):
            if j.get(m):
                mac(f"Acc{code}{tag}", f3(j[m]["acc"]), f"{proto} {m} target acc")
                mac(f"Std{code}{tag}", f3(j[m]["acc_std"]), f"{proto} {m} seed std")
                mac(f"Gap{code}{tag}", f3(j[m]["gap_cnn"]), f"{proto} {m} gap vs CNN")
        if j.get("gad_noalign"):
            mac(f"GapAlign{code}", f3(j["gad_noalign"]["gap_cnn"]), "gap -align vs CNN")
        if j.get("gad_notemporal"):
            mac(f"GapTemp{code}", f3(j["gad_notemporal"]["gap_cnn"]), "gap -temporal vs CNN")
        if j.get("gad_noanchor"):
            mac(f"GapAnchor{code}", f3(j["gad_noanchor"]["gap_cnn"]), "gap -anchor vs CNN")

# ---------------------------------------------------------------- audit
def _usable(p):
    j = cross.get(p)
    return bool(j and j.get("gad") and j["gad"]["acc"] >= 0.6)

audit = {p: load(f"audit_{p}.json") for p in PROTO}
aud_done = [p for p in PRIMARY if audit.get(p) and _usable(p)]
if aud_done:
    flips = [audit[p][f"{d}_d1.0"]["flip"]
             for p in aud_done for d in DESC
             if audit[p].get(f"{d}_d1.0")]
    if flips:
        mac("FlipScale", f"{100 * sum(flips) / len(flips):.0f}\\%",
            "typical flip rate under perturbation")

# ================================================================ tables
# --- tab_screen ---
if screen:
    cols = [p for p in PRIMARY if p in screen]
    lines = [r"\begin{tabular}{l" + "c" * len(cols) + "}", r"\toprule",
             "Descriptor & " + " & ".join(PROTO[p][1] for p in cols) + r" \\",
             r"\midrule"]
    for d in DESC:
        row = [DESCL[d]] + [f3(screen[p][d]["w1"]) for p in cols]
        lines.append(" & ".join(row) + r" \\")
    lines.append(r"\midrule")
    row = ["Anchor"] + [DESCN[screen[p]["_anchor"]] for p in cols]
    lines.append(" & ".join(row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (TAB / "tab_screen.tex").write_text("\n".join(lines) + "\n")

# --- tab_cross ---
if done:
    cols = [p for p in PRIMARY if p in done]
    lines = [r"\begin{tabular}{l" + "cc" * len(cols) + "}", r"\toprule",
             r"Method & " + " & ".join(
                 r"\multicolumn{2}{c}{" + PROTO[p][1] + "}" for p in cols) + r" \\",
             r"\cmidrule(lr){2-3}" + "".join(r"\cmidrule(lr){%d-%d}" % (2 + 2 * i, 3 + 2 * i)
                 for i in range(1, len(cols))) if len(cols) > 1 else r"",
             r" & " + " & ".join("Acc. & Gap" for _ in cols) + r" \\", r"\midrule"]
    for m in MODELS:
        row = [MLABEL[m]]
        for p in cols:
            cell = cross[p].get(m)
            if cell:
                row += [f3(cell["acc"]), f"{cell['gap_cnn']:+.3f}"]
            else:
                row += ["n/a", "n/a"]
        lines.append(" & ".join(row) + r" \\")
        if m == "dynhg":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (TAB / "tab_cross.tex").write_text("\n".join(lines) + "\n")

# --- tab_ablation (components; resolvable on cwru_0123) ---
if done:
    cols = [p for p in PRIMARY if p in done]
    abl = ["gad", "gad_noalign", "gad_notemporal", "gad_noanchor"]
    lines = [r"\begin{tabular}{l" + "cc" * len(cols) + "}", r"\toprule",
             r"Variant & " + " & ".join(
                 r"\multicolumn{2}{c}{" + PROTO[p][1] + "}" for p in cols) + r" \\",
             r"\cmidrule(lr){2-3}" + "".join(r"\cmidrule(lr){%d-%d}" % (2 + 2 * i, 3 + 2 * i)
                 for i in range(1, len(cols))) if len(cols) > 1 else r"",
             r" & " + " & ".join("Acc. & $\Delta$" for _ in cols) + r" \\",
             r"\midrule"]
    for m in abl:
        row = [MLABEL[m]]
        for p in cols:
            cell = cross[p].get(m)
            full = cross[p].get("gad")
            if cell and full:
                row += [f3(cell["acc"]), f"{cell['acc'] - full['acc']:+.3f}"]
            else:
                row += ["n/a", "n/a"]
        lines.append(" & ".join(row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (TAB / "tab_ablation.tex").write_text("\n".join(lines) + "\n")

# --- tab_audit (usable primary protocols) ---
if aud_done:
    lines = [r"\begin{tabular}{llccc}", r"\toprule",
             r"Protocol & Descriptor & $\delta{=}0.5$ & $\delta{=}1.0$ & $\delta{=}2.0$ \\",
             r"\midrule"]
    for p in aud_done:
        a = audit[p]
        anchor = a.get("anchor")
        for d in DESC:
            star = r"$^{*}$" if d == anchor else ""
            flips = [a.get(f"{d}_d{de}") for de in (0.5, 1.0, 2.0)]
            row = [r"\multirow{3}{*}{" + PROTO[p][1] + "}" if d == "kappa" else "",
                   f"{DESCL[d]}{star}"]
            for fl in flips:
                row.append(f"{fl['flip']:.2f}" if fl else "n/a")
            lines.append(" & ".join(row) + r" \\")
        lines.append(r"\cmidrule(lr){1-5}")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    (TAB / "tab_audit.tex").write_text("\n".join(lines) + "\n")

(MAN / "macros.tex").write_text("\n".join(macros) + "\n")
print("wrote macros.tex", len(macros), "lines")
print("main protocols:", [p for p in PRIMARY if p in done])
for f in sorted(TAB.glob("*.tex")):
    print("wrote", f.name)
